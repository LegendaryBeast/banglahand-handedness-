#!/usr/bin/env python3
"""Macros and Supplementary Table S4 for the adjusted-estimate inference and the class-specific recalls (IJDAR).

Inputs (all saved results; nothing is refitted here):
  results/ijdar_dev_2026-11-12/adjusted_inference/summary.json   (scripts/run_adjusted_inference.py)
  results/ijdar_dev_2026-11-12/linefree_secondary/writer_predictions.csv.gz   (line-free HC-183, SVM, condition A)
  results/csafe_ijdar_2026-11-12/csafe_metrics_summary.csv        (HC-183 text block, SVM, conditions A and X)
Outputs: manuscripts/ijdar/figures/adjusted_macros.tex and the table_adjusted_inference block of supplementary.tex.
Recalls are means over the 20 repetitions; the positive likelihood ratio is mean left recall / (1 - mean right recall)
with left-handedness as the positive class.
"""
import json
import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DEV = ROOT / "results/ijdar_dev_2026-11-12"
MS = ROOT / "manuscripts/ijdar"


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def pval(p):
    return f"{p:.3f}"


def main():
    rec = json.loads((DEV / "adjusted_inference/summary.json").read_text())
    R = {(r["case"], r["condition"]): r for r in rec}
    m = ["% Generated by scripts/make_ijdar_adjusted_macros.py from adjusted_inference/summary.json and saved predictions."]

    def put(name, val):
        m.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    tags = {("bh_ink", "A"): "BhInk", ("bh_framing", "A"): "BhFrame", ("cs_ink", "A"): "CsInk", ("cs_ink", "X"): "CsInkX",
            ("cs_all", "A"): "CsAll", ("cs_all", "X"): "CsAllX", ("cs_orientation", "A"): "CsOri",
            ("cs_orientation", "X"): "CsOriX", ("bh_whole", "A"): "BhWhole", ("lbp_ink", "A"): "Lbp"}
    for k, t in tags.items():
        r = R[k]
        put(f"vAi{t}A", pct(r["ba"])); put(f"vAi{t}Lo", f"{100 * r['ci_low']:.0f}"); put(f"vAi{t}Hi", f"{100 * r['ci_high']:.0f}")
        put(f"vAi{t}RecL", pct(r["recall_left"])); put(f"vAi{t}RecR", pct(r["recall_right"]))
        if r.get("p") is not None:
            put(f"vAi{t}P", pval(r["p"]))
        if r.get("holm_p") is not None:
            put(f"vAi{t}Holm", pval(r["holm_p"]))
    cs = [R[k]["holm_p"] for k in [("cs_ink", "A"), ("cs_ink", "X"), ("cs_all", "A"), ("cs_all", "X")]]
    put("vAiCsHolmMax", pval(max(cs)))

    # class-specific recall and positive likelihood ratio of the main estimates
    w = pd.read_csv(DEV / "linefree_secondary/writer_predictions.csv.gz")
    d = w[(w.rep == "hc183_lf") & (w.clf == "svm") & (w.analysis == "A")]
    assert d.groupby("seed").writer_id.nunique().eq(42).all() and d.seed.nunique() == 20
    se = d[d.label == 1].groupby("seed").pred.apply(lambda s: (s == 1).mean()).mean()
    sp = d[d.label == 0].groupby("seed").pred.apply(lambda s: (s == 0).mean()).mean()
    assert abs((se + sp) / 2 - 0.705) < 6e-4
    put("vRecBhL", pct(se)); put("vRecBhR", pct(sp)); put("vLrBh", f"{se / (1 - sp):.1f}")
    put("vLrNegBh", f"{(1 - se) / sp:.2f}")
    c = pd.read_csv(ROOT / "results/csafe_ijdar_2026-11-12/csafe_metrics_summary.csv")
    for an, t in (("A", "Cs"), ("X", "CsX")):
        x = c[(c.rep == "hc183_tb") & (c.clf == "svm") & (c.analysis == an)].iloc[0]
        put(f"vRec{t}L", pct(x.recall_left)); put(f"vRec{t}R", pct(x.recall_right))
        put(f"vLr{t}", f"{x.recall_left / (1 - x.recall_right):.1f}")
    (MS / "figures/adjusted_macros.tex").write_text("\n".join(m) + "\n")

    # Supplementary Table S4 rows
    rows = [("BanglaHand", "Line-free HC-183", "Ink density + photo intensity", ("bh_ink", "A")),
            ("", "", "+ 13 framing measures", ("bh_framing", "A")),
            ("", "Whole-photograph HC-183", "Ink density + photo intensity", ("bh_whole", "A")),
            ("CSAFE", "HC-183, A", "Ink density + scan intensity", ("cs_ink", "A")),
            ("", "HC-183, X", "Ink density + scan intensity", ("cs_ink", "X")),
            ("", "HC-183, A", "16 layout + ink + scan", ("cs_all", "A")),
            ("", "HC-183, X", "16 layout + ink + scan", ("cs_all", "X")),
            ("", "HC-183, A", "Line orientation (3)", ("cs_orientation", "A")),
            ("", "HC-183, X", "Line orientation (3)", ("cs_orientation", "X")),
            ("BanglaHand", "Uniform LBP (baseline)", "Ink density + photo intensity", ("lbp_ink", "A"))]
    body = []
    for ds, rep, cov, k in rows:
        r = R[k]
        p = pval(r["p"]) + ("$^{b}$" if k[0] == "lbp_ink" else "") if r.get("p") is not None else "--$^{a}$"
        h = pval(r["holm_p"]) if r.get("holm_p") is not None else "--"
        body.append(f"{ds} & {rep} & {cov} & {pct(r['ba'])} & {100 * r['ci_low']:.0f}--{100 * r['ci_high']:.0f} & "
                    f"{pct(r['recall_left'])} & {pct(r['recall_right'])} & {p} & {h} \\\\")
        if k == ("bh_whole", "A"):
            body.append("\\addlinespace[2pt]")
        if k == ("cs_orientation", "X"):
            body.append("\\addlinespace[2pt]")
    s = (MS / "supplementary.tex").read_text()
    new = "% BEGIN table_adjusted_inference\n" + "\n".join(body) + "\n% END table_adjusted_inference"
    s, n = re.subn(r"% BEGIN table_adjusted_inference.*?% END table_adjusted_inference", lambda _: new, s, flags=re.S)
    assert n == 1, "marker table_adjusted_inference not found in supplementary.tex"
    (MS / "supplementary.tex").write_text(s)
    print("\n".join(m[1:]))


if __name__ == "__main__":
    main()
