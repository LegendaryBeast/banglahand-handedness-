#!/usr/bin/env python3
"""IJDAR Tables 1-3: a line-free text-block block (primary) above the whole-photograph rows of the PRL study.

Line-free rows come from results/ijdar_dev_2026-11-12/linefree_table_rows*.csv (run_linefree_primary.py) and, for the
fine-tuned ResNet-18, from linefree_finetune/finetune_grey_summary.csv and finetune_grey_pitfalls.csv
(run_linefree_finetune.py + summarise_finetuned_grey_cnn.py). Whole-photograph rows are the PRL table rows
(manuscripts/ijdar/figures/table_*.tex, generated by make_prl_figures_v2.py), unchanged.
Writes manuscripts/ijdar/figures/table_{main,pitfalls,text}_ijdar.tex and pastes them into the manuscript between
% BEGIN / % END markers.
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DEV = ROOT / "results/ijdar_dev_2026-11-12"
FIG = ROOT / "manuscripts/ijdar/figures"
NAME = {"hc183_lf": "HC-183", "stroke_lf": "STROKE", "resnet18_lf": "ResNet-18", "efficientnet_b0_lf": "EffNet-B0",
        "vit_b_16_lf": "ViT-B/16"}
ORDER = ["hc183_lf", "stroke_lf", "resnet18_lf", "efficientnet_b0_lf", "vit_b_16_lf"]
f1 = lambda v: f"{100 * v:.1f}"
fs = lambda v, s: f"{100 * v:.1f}$\\pm${100 * s:.1f}"
sgn = lambda v: "0.0" if abs(v) < 0.0005 else (f"+{100 * v:.1f}" if v > 0 else f"$-${abs(100 * v):.1f}")


def head(text, ncol):
    return f"\\multicolumn{{{ncol}}}{{l}}{{\\emph{{{text}}}}} \\\\"


def main():
    R = pd.concat([pd.read_csv(f) for f in sorted(DEV.glob("linefree_table_rows*.csv"))]).drop_duplicates("rep", keep="last").set_index("rep")
    ft_dir = DEV / "linefree_finetune"
    fts = pd.read_csv(ft_dir / "finetune_grey_summary.csv").set_index("readout") if (ft_dir / "finetune_grey_summary.csv").exists() else None
    ftp = pd.read_csv(ft_dir / "finetune_grey_pitfalls.csv").iloc[0] if (ft_dir / "finetune_grey_pitfalls.csv").exists() else None
    reps = [r for r in ORDER if r in R.index]
    main_rows, pit_rows = [head("Line-free text block (printed lines removed; primary)", 9)], [head("Line-free text block (printed lines removed; primary)", 10)]
    for r in reps:
        x = R.loc[r]; nm = NAME[r] if r != "hc183_lf" else "\\textbf{HC-183}"
        main_rows.append(f"{nm} & {fs(x.A, x.A_sd)} & {100 * x.ci_low:.0f}--{100 * x.ci_high:.0f} & {f1(x.LR)} & {f1(x.RF)} & "
                         f"{fs(x.C, x.C_sd)} & {fs(x.B, x.B_sd)} & {fs(x.ALL8, x.ALL8_sd)} & {x.auc:.2f} \\\\")
        pit_rows.append(f"{nm} & {f1(x.A)} & {x.p:.3f} & {f1(x.adjusted)} & {f1(x.time_adj)} & {f1(x.acq_time)} & "
                        f"{f1(x.para_ba_writer)} & {f1(x.para_ba_leaky)} & {f1(x.writer_id_top1)} & {sgn(x.C_minus_D)} / {sgn(x.B_minus_E)} \\\\")
    if fts is not None:
        g = lambda k, sd=True: (fs(fts.loc[k, "ba_mean"], fts.loc[k, "ba_sd"]) if sd else f1(fts.loc[k, "ba_mean"])) if k in fts.index else "--"
        s = fts.loc["svm_A"]
        main_rows.append(f"ResNet-18 (fine-tuned) & {g('svm_A')} & {100 * s.ci_low:.0f}--{100 * s.ci_high:.0f} & {g('logistic_A', False)} & "
                         f"{g('random_forest_A', False)} & {g('svm_C')} & {g('svm_B')} & {g('svm_ALL8')} & {s.auc_mean:.2f} \\\\")
        pv = lambda k: f1(ftp[k]) if ftp is not None else "--"
        con = f"{sgn(ftp.transfer_C_minus_D)} / {sgn(ftp.varied_B_minus_E)}" if ftp is not None else "--"
        pit_rows.append(f"ResNet-18 (fine-tuned) & {f1(fts.loc['svm_A', 'ba_mean'])} & -- & {f1(fts.loc['svm_adj_A', 'ba_mean'])} & "
                        f"{pv('time_adj')} & {pv('acq_time')} & {pv('para_ba_writer_split')} & -- & {pv('writer_id_top1')} & {con} \\\\")
    main_rows += ["\\addlinespace[3pt]", head("Whole photograph (as in the earlier analysis)", 9)] + (FIG / "table_main.tex").read_text().strip().splitlines()
    pit_rows += ["\\addlinespace[3pt]", head("Whole photograph (as in the earlier analysis)", 10)] + (FIG / "table_pitfalls.tex").read_text().strip().splitlines()
    (FIG / "table_main_ijdar.tex").write_text("\n".join(main_rows) + "\n")
    (FIG / "table_pitfalls_ijdar.tex").write_text("\n".join(pit_rows) + "\n")
    text_rows = []
    for r in [r for r in ("hc183_lf", "stroke_lf") if r in R.index]:
        x = R.loc[r]
        text_rows.append(f"{NAME[r]} (line-free) & {f1(x.A)} & {f1(x.D_S1)} & {f1(x.D_S2)} & {f1(x.D_S3)} & {f1(x.C)} & {sgn(x.C_minus_D)} & "
                         f"{f1(x.E_S1)} & {f1(x.E_S2)} & {f1(x.E_S3)} & {f1(x.B)} & {sgn(x.B_minus_E)} \\\\")
    text_rows.append("\\addlinespace[2pt]")
    text_rows += [l.replace("HC-183 &", "HC-183 (whole photo) &", 1).replace("STROKE &", "STROKE (whole photo) &", 1)
                  for l in (FIG / "table_text.tex").read_text().strip().splitlines()]
    (FIG / "table_text_ijdar.tex").write_text("\n".join(text_rows) + "\n")
    inject(ROOT / "manuscripts/ijdar/ijdar_manuscript.tex")
    print((FIG / "table_main_ijdar.tex").read_text())


def inject(tex):
    """Paste each generated table body between its % BEGIN / % END markers (\\input cannot precede \\multicolumn).
    The pitfall and text-condition tables live in the supplementary file (Online Resource 1) next to the manuscript."""
    for f in (tex, tex.with_name("supplementary.tex")):
        if not f.exists():
            continue
        t = f.read_text()
        for k in ("table_main_ijdar", "table_pitfalls_ijdar", "table_text_ijdar"):
            b, e = f"% BEGIN {k}\n", f"% END {k}\n"
            if b in t:
                i, j = t.index(b) + len(b), t.index(e)
                t = t[:i] + (FIG / f"{k}.tex").read_text() + t[j:]
        f.write_text(t)


if __name__ == "__main__":
    main()
