#!/usr/bin/env python3
"""Build the two archive packages in release/ (the paper submissions and the Kaggle zip have their own builders).

release/dataset/bangla_handedness_paragraphs_v1.zip   the released dataset, for the repository deposit (Mendeley Data / Zenodo)
release/code/handedness_code_and_results.zip          code, notebooks, tests, saved results and manuscript sources;
                                                      everything needed to regenerate every number, table and figure
Excluded from the code package: images (in the dataset package), camera originals, run logs and the internal protocol notes.
"""
import hashlib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REL = ROOT / "release"
SKIP_NAMES = {".DS_Store"}
SKIP_PARTS = {"__pycache__", ".pytest_cache", "logs", "protocol"}
CODE_ITEMS = ["README.md", "REPRODUCIBILITY.md", "requirements.txt", "scripts", "tests", "notebooks",
              "results/final42_2026-10-19", "audit/geometric", "audit/fix_log.tsv", "audit/writer_level_stats_44_folders.csv",
              "manuscripts/prl", "manuscripts/data_in_brief"]
MANUSCRIPT_JUNK = (".aux", ".log", ".out", ".spl", ".blg")
RELEASE_README = """# Release packages

| Package | Where it goes |
|---|---|
| `prl_submission.zip` (folder `prl_submission/`) | Pattern Recognition Letters submission: LaTeX source, compiled PDF, figures, cover letter, highlights |
| `dib_submission.zip` (folder `dib_submission/`) | Data in Brief submission: LaTeX source, compiled PDF, figures |
| `dataset/bangla_handedness_paragraphs_v1.zip` | data repository deposit (Mendeley Data or Zenodo, CC BY 4.0 proposed); put the DOI into the DiB article |
| `code/handedness_code_and_results.zip` | code, notebooks, tests, saved results and manuscript sources; reproduces every number (see REPRODUCIBILITY.md inside) |
| `kaggle/` | Kaggle dataset zip (data + code + ImageNet weights) and the two notebooks (see kaggle/KAGGLE_README.md) |
| `SHA256SUMS.txt` | checksums of the zip files |

All packages are generated by scripts/make_submission_folders.py, scripts/make_kaggle_package.py and scripts/make_release_packages.py.
"""


def files(item):
    p = ROOT / item
    for f in ([p] if p.is_file() else sorted(p.rglob("*"))):
        if f.is_file() and f.name not in SKIP_NAMES and not SKIP_PARTS & set(f.relative_to(ROOT).parts) and f.suffix not in MANUSCRIPT_JUNK:
            yield f


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for c in iter(lambda: fh.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def main():
    out = REL / "dataset"; out.mkdir(parents=True, exist_ok=True)
    z1 = out / "bangla_handedness_paragraphs_v1.zip"
    with zipfile.ZipFile(z1, "w", zipfile.ZIP_STORED) as z:          # JPEGs do not compress further
        for f in files("dataset"):
            z.write(f, "bangla_handedness_paragraphs_v1/" + str(f.relative_to(ROOT / "dataset")))
    with zipfile.ZipFile(z1) as z:
        n = sum(1 for i in z.infolist() if i.filename.endswith(".jpg"))
    print(f"{z1.relative_to(ROOT)}: {n} images, {z1.stat().st_size / 1e9:.2f} GB")

    out = REL / "code"; out.mkdir(parents=True, exist_ok=True)
    z2 = out / "handedness_code_and_results.zip"
    with zipfile.ZipFile(z2, "w", zipfile.ZIP_DEFLATED) as z:
        k = 0
        for item in CODE_ITEMS:
            for f in files(item):
                z.write(f, "handedness_code_and_results/" + str(f.relative_to(ROOT))); k += 1
    print(f"{z2.relative_to(ROOT)}: {k} files, {z2.stat().st_size / 1e6:.0f} MB")

    (REL / "README.md").write_text(RELEASE_README)
    lines = [f"{sha(p)}  {p.relative_to(REL)}" for p in sorted(REL.rglob("*.zip"))]
    (REL / "SHA256SUMS.txt").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
